public class bola { 
    private String nama;
    private int  hari;
    private int  harga;

    public void bola(String nama, int hari, int harga) {
        this.nama = nama;
        this.hari = hari;
        this.harga = harga;
    }

    public String getNama() {
        return nama;
    }

    public int getHari() {
        return hari;
    }

    public int getHarga() {
        return harga;
    }
    

}
